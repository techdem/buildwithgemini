import json
import logging
import os
import uuid
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

# Hardcode project and bucket name as strings
PROJECT_ID = "qwiklabs-gcp-02-5562d69b56d9"
BUCKET_NAME = "smart-recipe-assets-qwiklabs-gcp-02-5562d69b56d9"
MODEL_NAME = "gemini-3.1-flash-lite-image"

logger = logging.getLogger(__name__)

def generate_recipe_image(dish_name: str, tool_context: ToolContext) -> str:
    """Generates an image for a recipe or dish using gemini-3.1-flash-lite-image model, saves it as a session artifact, uploads it to Cloud Storage, and returns its public HTTPS URL."""
    try:
        # 1. Initialize GenAI client for global region
        client = genai.Client(
            vertexai=True,
            project=PROJECT_ID,
            location="global"
        )

        prompt = f"A professional food photograph of {dish_name}, freshly prepared, high resolution, beautifully plated."
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=prompt
        )

        image_bytes = None
        mime_type = "image/jpeg"

        if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
            for part in response.candidates[0].content.parts:
                if part.inline_data:
                    image_bytes = part.inline_data.data
                    if part.inline_data.mime_type:
                        mime_type = part.inline_data.mime_type
                    break

        if not image_bytes:
            return json.dumps({
                "status": "ERROR",
                "dish_name": dish_name,
                "message": "No image data was generated by the model."
            })

        # Generate unique filename for artifact and object
        slug = dish_name.lower().replace(" ", "_")[:20]
        ext = "png" if "png" in mime_type else "jpg"
        unique_id = uuid.uuid4().hex[:6]
        filename = f"{slug}_{unique_id}.{ext}"

        # 2. Save artifact in ToolContext for Playground Artifacts panel
        part_artifact = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
        tool_context.save_artifact(filename=filename, artifact=part_artifact)

        # 3. Upload image bytes directly to Cloud Storage bucket without local disk write
        gcs_client = storage.Client(project=PROJECT_ID)
        bucket = gcs_client.bucket(BUCKET_NAME)
        blob_path = f"recipe_images/{filename}"
        blob = bucket.blob(blob_path)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{blob_path}"

        return json.dumps({
            "status": "SUCCESS",
            "dish_name": dish_name,
            "filename": filename,
            "public_url": public_url,
            "mime_type": mime_type,
            "message": f"Successfully generated image for '{dish_name}'."
        }, indent=2)

    except Exception as e:
        logger.error(f"Image generation tool error: {e}", exc_info=True)
        return json.dumps({
            "status": "ERROR",
            "dish_name": dish_name,
            "message": f"Image generation failed: {str(e)}"
        })
